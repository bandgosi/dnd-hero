/* =========================================================
   data/characters.js — персонажи-помощники и их реплики.
   Реплики никогда не содержат слова «неправильно».
   ========================================================= */
(function (global) {
  'use strict';

  var CHARACTERS = [
    { id: 'fox',   emoji: '🦊', name: 'Лисёнок Рыжик', hello: 'Привет! Я Рыжик. Давай учиться вместе!' },
    { id: 'owl',   emoji: '🦉', name: 'Совёнок Умник', hello: 'Ух-ух! Я Умник. Мне нравится узнавать новое!' },
    { id: 'cat',   emoji: '🐱', name: 'Котёнок Мурзик', hello: 'Мяу! Я Мурзик. Будем играть и учиться!' },
    { id: 'robot', emoji: '🤖', name: 'Робот Бип', hello: 'Бип-бип! Я Бип. Готов помогать!' }
  ];

  var LINES = {
    greetNew:   ['Привет! Как тебя зовут?'],
    greetBack:  ['Рад тебя видеть, {name}!', 'Привет, {name}! Продолжим?', 'Здорово, что ты пришёл, {name}!'],
    startLesson:['Начинаем! Я рядом.', 'Поехали! У тебя получится.', 'Давай попробуем вместе.'],
    right:      ['Верно!', 'Отлично!', 'Молодец!', 'Точно!', 'Здорово!', 'Так и есть!'],
    soft:       ['Почти! Давай попробуем ещё раз.',
                 'Хорошая попытка! Посмотри внимательно.',
                 'Уже близко! Попробуем снова.',
                 'Ничего страшного. Ещё разок?'],
    reveal:     ['Смотри, вот правильный ответ. Запомним!',
                 'Вот как надо. В следующий раз получится!'],
    unitDone:   ['Ты справился! Идём дальше.', 'Урок пройден! Я горжусь тобой.', 'Ура! Мы закончили.'],
    dailyDone:  ['Ты молодец! Тренировка закончена!'],
    streak:     ['Ты занимаешься {n} дня подряд! Здорово!'],
    thinking:   ['Не спеши, подумай.', 'Посмотри ещё раз на картинку.'],
    writeStart: ['Веди пальчиком от зелёной точки.', 'Начни с зелёной точки и веди по дорожке.'],
    writeGood:  ['Красивая буква получилась!', 'Отличное письмо!'],
    writeAgain: ['Давай проведём ещё раз, аккуратно.']
  };

  function pick(a) { return a[Math.floor(Math.random() * a.length)]; }

  global.Characters = {
    LIST: CHARACTERS,
    byId: function (id) {
      for (var i = 0; i < CHARACTERS.length; i++) if (CHARACTERS[i].id === id) return CHARACTERS[i];
      return CHARACTERS[0];
    },
    line: function (key, vars) {
      var arr = LINES[key];
      if (!arr) return '';
      var s = pick(arr);
      Object.keys(vars || {}).forEach(function (k) {
        s = s.replace('{' + k + '}', vars[k]);
      });
      return s;
    },
    LINES: LINES
  };

})(window);
