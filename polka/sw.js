self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE_NAME).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

async function warmAudio() {
  const c = await caches.open(CACHE_NAME);
  for (let i = 0; i < AUDIO.length; i += 25) {
    await Promise.all(AUDIO.slice(i, i + 25).map(async (u) => {
      try {
        if (await c.match(u)) return;
        const r = await fetch(u);
        if (r.ok) await c.put(u, r);
      } catch (e) { /* без сети дольёмся в следующий раз */ }
    }));
  }
}

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('polka-') && k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
      .then(() => warmAudio())
  );
});

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(e.request).then((r) => {
        // услышанный клип сразу остаётся в офлайне
        if (r.ok && e.request.url.indexOf('/audio/') !== -1) {
          const copy = r.clone();
          caches.open(CACHE_NAME).then((c) => c.put(e.request, copy));
        }
        return r;
      });
    })
  );
});
